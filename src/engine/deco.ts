/** classic donut.c torus into the char grid */
export function drawDonut(
  g: Grid, cx: number, cy: number, halfW: number, A: number, B: number,
): void {
  const zb = new Float32Array(g.cols * g.rows);
  const out = new Int8Array(g.cols * g.rows).fill(-1);
  for (let j = 0; j < 6.283; j += 0.07) {
    for (let i = 0; i < 6.283; i += 0.02) {
      const c = Math.sin(i), d = Math.cos(j), e = Math.sin(A), f = Math.sin(j);
      const gg = Math.cos(A), h = d + 2;
      const D = 1 / (c * h * e + f * gg + 5);
      const l = Math.cos(i), m = Math.cos(B), n = Math.sin(B), t = c * h * gg - f * e;
      const x = (cx + halfW * D * (l * h * m - t * n)) | 0;
      const y = (cy + halfW * 0.62 * D * (l * h * n + t * m)) | 0;
      let Nv = Math.floor(8 * ((f * e - c * d * gg) * m - c * d * e - f * gg - l * d * n));
      if (Nv < 0) Nv = 0; if (Nv > 11) Nv = 11;
      if (y >= 0 && y < g.rows && x >= 0 && x < g.cols && D > zb[y * g.cols + x]) {
        zb[y * g.cols + x] = D; out[y * g.cols + x] = Nv;
      }
    }
  }
  for (let y = 0; y < g.rows; y++) {
    for (let x = 0; x < g.cols; x++) {
      const Nv = out[y * g.cols + x];
      if (Nv >= 0) g.put(x, y, '.,-~:;=!*#$@'[Nv], Nv < 4 ? 1 : Nv < 8 ? 2 : 3);
    }
  }
}

