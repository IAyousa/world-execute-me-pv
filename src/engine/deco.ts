/** ASCII heart — generated by scripts/ascii_art.py (implicit-curve sampled,
 *  density ramp ' .:-=+*#%@', brighter cell = denser glyph, auto color index) */
const RAMP_DENSITY = ' .:-=+*#%@';
function densityCi(ch: string): number {
  const pos = RAMP_DENSITY.indexOf(ch);
  if (pos < 1) return 2;
  return Math.max(1, Math.min(4, 1 + Math.round((pos / (RAMP_DENSITY.length - 1)) * 3)));
}
export function drawHeart(g: Grid, cx: number, cy: number, sc: number, _ci = 4): void {
  const w = HEART[0].length * sc, h = HEART.length * sc;
  const x0 = Math.round(cx - w / 2), y0 = Math.round(cy - h / 2);
  for (let r = 0; r < HEART.length; r++) {
    for (let c = 0; c < HEART[r].length; c++) {
      const chr = HEART[r][c];
      if (chr === ' ') continue;
      for (let dy = 0; dy < sc; dy++) {
        for (let dx = 0; dx < sc; dx++) {
          g.put(x0 + c * sc + dx, y0 + r * sc + dy, chr, densityCi(chr));
        }
      }
    }
  }
}

/** viewfinder / gun-sight corner brackets; dotted=true adds the faint dotted border */
export function viewfinder(
  g: Grid, x0: number, y0: number, x1: number, y1: number,
  ci = 4, arm = 3, dotted = true,
): void {
  for (let k = 0; k <= arm; k++) {
    g.put(x0 + k, y0, k === 0 ? '┌' : '─', ci);
    g.put(x1 - k, y0, k === 0 ? '┐' : '─', ci);
    g.put(x0 + k, y1, k === 0 ? '└' : '─', ci);
    g.put(x1 - k, y1, k === 0 ? '┘' : '─', ci);
  }
  if (!dotted) return;
  for (let x = x0 + arm + 1; x < x1 - arm; x++) {
    if (x % 3 === 0) { g.put(x, y0, '·', 1); g.put(x, y1, '·', 1); }
  }
  for (let y = y0 + arm + 1; y < y1 - arm; y++) {
    if (y % 3 === 0) { g.put(x0, y, '·', 1); g.put(x1, y, '·', 1); }
  }
}

/** typed lyric inside a C-style comment block */
export function commentBlock(
  g: Grid, x: number, y: number, text: string, typedChars: number, ci = 3,
): void {
  const shown = text.slice(0, Math.max(0, typedChars));
  const vis = `/* ${shown}`;
  g.puts(x, y, vis, ci);
  if (typedChars >= text.length) g.puts(x + vis.length, y, ' */', ci);
  else if (typedChars > 0 && Math.floor(typedChars * 0.7) % 2 === 0) g.put(x + vis.length, y, '▌', 4);
}

const PSEUDO_WORDS = ['world', 'me', 'you', 'execute', 'love', 'return', 'import',
  'static', 'void', 'wait', 'run', 'if', 'else', 'while', 'true', 'false', 'null',
  'heart', 'pain', 'sim', 'new', 'delete', 'this', 'sync', 'async'];

/** decorative unreadable pseudo-code rain (official-MV density philosophy) */
export function pseudoBg(g: Grid, t: number, seed: number, density = 0.3): void {
  const scroll = Math.floor(t * 3);
  for (let x = 2; x < g.cols - 2; x++) {
    if (Math.floor(hash(x * 7 + seed, 1) * 3) !== 0) continue; // sparse columns
    for (let y = 0; y < g.rows; y++) {
      const r = hash(x * 131 + ((y + scroll) % 97), seed);
      if (r > density) continue;
      const w = PSEUDO_WORDS[Math.floor(hash(x + y * 17 + scroll, seed + 2) * PSEUDO_WORDS.length)];
      g.put(x, y, w[0], 1);
    }
  }
}

/** synthetic waveform strip (bottom rows) */
export function waveStrip(g: Grid, t: number, rows = 3, y0 = -1): void {
  const top = y0 >= 0 ? y0 : g.rows - 2 - rows;
  for (let x = 0; x < g.cols; x++) {
    const v = waveAt(t + (x - g.cols / 2) * 0.012);
    const h = Math.min(rows, Math.round(v * rows * 2.2));
    for (let k = 0; k < h; k++) {
      g.put(x, top + rows - 1 - k, '▁▂▃▄▅▆▇█'[Math.min(7, Math.floor((k / Math.max(1, rows)) * 8))], k >= rows - 1 ? 4 : 3);
    }
  }
}

/** glitch pass: corrupt cells + band shift, deterministic per frame */
export function glitchPass(g: Grid, amt: number, frame: number): void {
  if (amt < 0.03) return;
  const GL = '!<>-_\\/[]{}=+*^?#$%&@01';
  const n = Math.floor(amt * g.cols * g.rows * 0.025);
  for (let k = 0; k < n; k++) {
    const x = Math.floor(hash(frame * 31 + k, 1) * g.cols);
    const y = Math.floor(hash(frame * 17 + k, 2) * g.rows);
    g.put(x, y, GL[Math.floor(hash(k, frame + 3) * GL.length)], hash(k + 9, frame) < 0.25 ? 5 : 3);
  }
  if (hash(frame, 44) < amt * 0.7) {
    const y0 = Math.floor(hash(frame, 5) * (g.rows - 6));
    const hh = 2 + Math.floor(hash(frame, 6) * 3 * amt);
    const sh = (1 + Math.floor(hash(frame, 7) * 4)) * (hash(frame, 8) < 0.5 ? -1 : 1);
    for (let y = y0; y < Math.min(g.rows, y0 + hh); y++) {
      const row: [string, number][] = [];
      for (let x = 0; x < g.cols; x++) row.push([g.ch[y * g.cols + x], g.col[y * g.cols + x]]);
      for (let x = 0; x < g.cols; x++) {
        const s = (x + sh + g.cols) % g.cols;
        g.ch[y * g.cols + x] = row[s][0]; g.col[y * g.cols + x] = row[s][1];
      }
    }
  }
}

/** big letterspaced monospace word on canvas ctx (still "all characters") */
export function bigWord(
  ctx: CanvasRenderingContext2D, word: string, cx: number, cy: number,
  size: number, fill: string, stroke?: string, spacing = 1.4,
): void {
  ctx.font = `bold ${size}px Consolas, "Courier New", monospace`;
  ctx.textBaseline = 'middle';
  const w = ctx.measureText('M').width * spacing;
  const total = word.length * w;
  let x = cx - total / 2;
  for (const c of word) {
    if (stroke) { ctx.strokeStyle = stroke; ctx.lineWidth = Math.max(2, size / 14); ctx.strokeText(c, x, cy); }
    ctx.fillStyle = fill;
    ctx.fillText(c, x, cy);
    x += w;
  }
}
